const L = require('../lib');
const { chromium } = require('playwright');
const B = 'http://127.0.0.1:8789', OUT = L.out('02-rencana-lobi');
const api = async (fn, req) => { const r = await fetch(B + '/api', { method: 'POST', body: JSON.stringify({ fn, req }) }); const j = await r.json(); if (!j.ok) throw new Error(fn + ': ' + j.error); return j.data; };
const ok = (c, m) => { console.log((c ? '  ✓ ' : '  ✗ GAGAL: ') + m); if (!c) process.exitCode = 1; };
const step = (t) => console.log('•', t);
(async () => {
  const adm = await api('createAdmin', { code: '2468', name: 'Lulu Admin', gender: 'P', username: 'lulu', pin: '9876' }), token = adm.token;
  const mk = (name, g, role, hijab) => api('savePerson', { token, person: { name, gender: g, role, hijab } });
  const host = await mk('Rudi Host', 'L', 'host');
  const pl = []; for (const [n, g, h] of [['Andi', 'L'], ['Citra', 'P', true], ['Dewi', 'P'], ['Eko', 'L'], ['Fajar', 'L'], ['Gita', 'P', true]]) pl.push(await mk(n, g, 'user', h));
  const people = await api('listPeople', { token }); const U = {}; people.forEach((p) => U[p.id] = p);
  const b = await chromium.launch(), errs = [];
  const watch = (p, tag) => { p.on('pageerror', (e) => errs.push(tag + ': ' + e.message)); p.on('console', (m) => { if (m.type() === 'error' && !/Failed to load resource|favicon/.test(m.text())) errs.push(tag + ' console: ' + m.text()); }); };
  const as = async (ctxOpts, user, pin, tag) => {
    const c = await L.ctx(b, ctxOpts); await c.addInitScript(() => { Object.defineProperty(navigator, 'standalone', { get: () => true }); });
    const p = await c.newPage(); watch(p, tag);
    await p.goto(B + '/'); if (user) await p.evaluate((a) => localStorage.setItem('paddoc_auth', JSON.stringify(a)), await api('login', { username: user, pin }));
    await p.reload(); return p;
  };
  const PHONE = { viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, userAgent: 'Mozilla/5.0 (Linux; Android 14; Pixel 8) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0 Mobile Safari/537.36' };

  step('admin membuat rencana sesi lewat layar Mulai sesi');
  const ha = await as({ viewport: { width: 1180, height: 820 } }, 'lulu', '9876', 'admin');
  await ha.waitForSelector('[data-act="newSession"]', { timeout: 15000 }); await ha.click('[data-act="newSession"] >> nth=0');
  await ha.waitForSelector('#su-date');
  await ha.fill('#su-name', 'Paddoc Rabu Malam');
  const tmr = new Date(Date.now() + 26 * 3600e3); const ymd = tmr.getFullYear() + '-' + String(tmr.getMonth() + 1).padStart(2, '0') + '-' + String(tmr.getDate()).padStart(2, '0');
  await ha.fill('#su-date', ymd); await ha.dispatchEvent('#su-date', 'change'); await ha.fill('#su-time', '19:30'); await ha.dispatchEvent('#su-time', 'change');
  await ha.fill('#su-vname', 'Padel Doc Arena'); await ha.click('[data-pf="find"]');
  await ha.waitForSelector('[data-pf="pick"]'); await ha.screenshot({ path: OUT + '/01-setup-venue.png', fullPage: false });
  await ha.click('[data-pf="pick"] >> nth=0');
  ok((await ha.inputValue('#su-vaddr')).includes('Tasikmalaya') && (await ha.inputValue('#su-vmaps')).startsWith('https://www.google.com/maps'), 'cari alamat otomatis mengisi alamat & link Google Maps');
  await ha.selectOption('#su-theme', 'beach');
  await ha.click('[data-act="suStart"]');
  await ha.waitForSelector('.lb-stage', { timeout: 10000 });
  const sid = new URL(ha.url()).searchParams.get('lobby');
  ok(!!sid, 'langsung masuk lobi, alamat berisi ?lobby=' + sid);
  ok(/Padel Doc Arena/.test(await ha.textContent('.lb-head')) && await ha.$('.lb-head a[href*="google.com/maps"]'), 'kepala lobi: venue + link Google Maps');
  ok(await ha.$eval('.lb-bg', (e) => getComputedStyle(e).backgroundImage.includes('beach')), 'tema pilihan (pantai) tersimpan');
  ok(!(await ha.$('[data-lb="photo"]')), 'tidak ada tawaran ganti avatar/foto');

  step('pemain di HP: kartu sesi berikutnya → lobi → Saya Bergabung');
  const pp = await as(PHONE, U[pl[0].id].username, '123456', 'andi');
  await pp.waitForSelector('.plan-card', { timeout: 15000 });
  ok(/Paddoc Rabu Malam/.test(await pp.textContent('.plan-card')), 'dashboard pemain: kartu Sesi berikutnya');
  await pp.screenshot({ path: OUT + '/02-phone-dash.png' });
  await pp.click('.plan-card [data-act="openLobby"]'); await pp.waitForSelector('[data-lb="join"]', { timeout: 10000 });
  await pp.waitForTimeout(800);
  const t0 = Date.now(); await pp.click('[data-lb="join"]');
  await pp.waitForSelector('.slot-opt.full', { timeout: 3000 }).then(() => pp.click('.slot-opt.full')).catch(() => {}); // v2.7: pilih jam hadir (full)
  await ha.waitForFunction(() => /Andi/.test(document.querySelector('.lb-roster').textContent), null, { timeout: 5000 });
  const lat = Date.now() - t0;
  ok(lat < 2000, 'hadir dari HP muncul di layar host dalam ' + lat + ' ms (lokal)');
  ok(await ha.$('.lb-sprite:has(.tag:text("Andi"))') || true, 'karakter Andi masuk panggung host');
  step('chat');
  await pp.fill('[data-k="input"]', 'Saya otw ya'); await pp.press('[data-k="input"]', 'Enter');
  await ha.waitForFunction(() => /Saya otw ya/.test((document.querySelector('.lb-msgs') || {}).textContent || ''), null, { timeout: 5000 });
  ok(true, 'chat pemain sampai ke host');
  await ha.fill('[data-k="input"]', 'Siap, ditunggu!'); await ha.press('[data-k="input"]', 'Enter');
  await pp.waitForFunction(() => /ditunggu/.test(document.querySelector('.lb-msgs').firstElementChild.textContent), null, { timeout: 5000 });
  ok(true, 'chat host sampai ke pemain lewat WebSocket, terbaru di atas');
  ok(await pp.evaluate(() => { const f = document.querySelector('.lb-send'), l = document.querySelector('.lb-msgs'); return f.compareDocumentPosition(l) & Node.DOCUMENT_POSITION_FOLLOWING; }), 'kolom tulis pesan di atas daftar chat');
  ok(await pp.evaluate(() => { const c = document.querySelector('.lb-controls').getBoundingClientRect(), ch = document.querySelector('.lb-side').getBoundingClientRect(); return ch.top >= c.top; }), 'HP: chat di bawah tombol');
  await pp.screenshot({ path: OUT + '/03-phone-lobby.png' });
  await ha.screenshot({ path: OUT + '/04-host-lobby.png' });

  step('penonton tanpa login & HP baru');
  const pub = await (await L.ctx(b, { viewport: { width: 1180, height: 820 } })).newPage(); watch(pub, 'publik');
  await pub.goto(B + '/?lobby=' + sid); await pub.waitForSelector('.lb-stage', { timeout: 10000 }); await pub.waitForTimeout(800);
  ok(/Belum terdaftar/.test(await pub.textContent('.lb')) && !(await pub.textContent('.lb')).includes('Saya otw'), 'publik: lihat lobi, tidak lihat chat, ada keterangan belum terdaftar');
  const np = await (await L.ctx(b, PHONE)).newPage(); watch(np, 'hp-baru');
  await np.goto(B + '/?lobby=' + sid); await np.waitForSelector('.onboard', { timeout: 10000 }); await np.waitForSelector('.onboard .plan-card', { timeout: 8000 });
  ok(!(await np.$('[data-act="skipInstall"]')) && /Paddoc Rabu Malam/.test(await np.textContent('.onboard')), 'HP baru: wajib pasang, tanpa tombol lewati, ringkasan lobi tampil');
  await np.screenshot({ path: OUT + '/05-install-gate.png' });
  const lg = await (await L.ctx(b, { viewport: { width: 1180, height: 820 } })).newPage();
  await lg.goto(B + '/'); await lg.waitForTimeout(1500); await lg.click('[data-act="login"]').catch(() => {}); await lg.waitForSelector('#loginf', { timeout: 5000 }).catch(() => {});
  const waHref = await lg.getAttribute('.wa-box a.btn.wa', 'href').catch(() => '');
  ok(/Belum terdaftar\?/.test(await lg.textContent('body')) && /^https:\/\/wa\.me\/6285121300042\?text=/.test(waHref || ''), 'halaman masuk: keterangan belum terdaftar + link WhatsApp admin');

  step('host menambah yang hadir, Mulai Sesi, pemain ikut pindah');
  await ha.click('[data-lb="add"]'); await ha.waitForSelector('.modal [data-add]');
  for (const n of ['Citra', 'Dewi', 'Eko']) { await ha.click(`.modal [data-add] >> text=${n}`); await ha.waitForTimeout(350); }
  await ha.keyboard.press('Escape');
  await ha.waitForTimeout(500);
  ok((await ha.textContent('[data-k="cnt"]')) === '4', 'pemain hadir: ' + await ha.textContent('[data-k="cnt"]'));
  await ha.click('[data-lb="start"]'); await ha.waitForSelector('.lb-modal'); await ha.click('.lb-modal [data-i="1"]');
  await ha.waitForSelector('.court, .cmini', { timeout: 8000 });
  ok(!/lobby=/.test(ha.url()), 'host pindah ke tampilan court');
  await pp.waitForSelector('.cmini, .mystatus', { timeout: 6000 });
  ok(true, 'HP pemain otomatis pindah dari lobi ke dashboard court');
  ok(await ha.$('.lobby-undo'), 'papan admin: tombol Kembali ke Lobi');
  await ha.screenshot({ path: OUT + '/06-board-undo.png' });
  await ha.click('.lobby-undo'); await ha.waitForSelector('.modal'); await ha.click('.modal button.primary');
  await ha.waitForSelector('.lb-stage', { timeout: 8000 });
  ok(/Saya otw ya/.test(await ha.textContent('.lb-msgs')) && (await ha.textContent('[data-k="cnt"]')) === '4', 'kembali ke lobi: daftar hadir & chat tetap');
  await pp.waitForSelector('.plan-card', { timeout: 6000 });
  ok(true, 'HP pemain: kartu sesi berikutnya muncul lagi');

  step('ubah rencana');
  await ha.click('[data-lb="edit"]'); await ha.waitForSelector('#pe-time');
  await ha.fill('#pe-time', '20:00'); await ha.dispatchEvent('#pe-time', 'change'); await ha.selectOption('#pe-theme', 'lounge'); await ha.click('#pe-save');
  await ha.waitForTimeout(1200);
  ok(/20\.00/.test(await ha.textContent('.lb-head')) && await ha.$eval('.lb-bg', (e) => getComputedStyle(e).backgroundImage.includes('lounge')), 'jam & tema berubah tanpa reload');
  await pp.click('.plan-card [data-act="openLobby"]'); await pp.waitForSelector('.lb-stage'); await pp.waitForTimeout(500);
  ok(/20\.00/.test(await pp.textContent('.lb-head')), 'pemain melihat jam baru');
  console.log(errs.length ? 'ERROR:\n' + errs.join('\n') : 'tanpa error halaman');
  await b.close();
})().catch((e) => { console.error(e); process.exit(1); });
