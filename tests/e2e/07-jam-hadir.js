const L = require('../lib');
const { chromium } = require('playwright');
const fs = require('fs'), path = require('path');
const B = 'http://127.0.0.1:8789', OUT = L.out('07-jam-hadir');
const api = async (fn, req) => { const r = await fetch(B + '/api', { method: 'POST', body: JSON.stringify({ fn, req }) }); const j = await r.json(); if (!j.ok) throw new Error(fn + ': ' + j.error); return j.data; };
const ok = (c, m) => { console.log((c ? '  ✓ ' : '  ✗ GAGAL: ') + m); if (!c) process.exitCode = 1; };
const step = (t) => console.log('•', t);
const asli = 'data:image/jpeg;base64,' + fs.readFileSync(L.fixture('asli.jpg')).toString('base64');
const hh = (t) => { const d = new Date(t); return String(d.getHours()).padStart(2, '0') + '.' + String(d.getMinutes()).padStart(2, '0'); };
(async () => {
  const adm = await api('createAdmin', { code: '2468', name: 'Lulu Admin', gender: 'P', username: 'lulu', pin: '9876' }), token = adm.token;
  const host = await api('savePerson', { token, person: { name: 'Rudi Hartono', gender: 'L', role: 'host' }, photoData: asli });
  const names = ['Andi', 'Budi', 'Citra', 'Dewi', 'Eko', 'Fajar', 'Gita', 'Hana'];
  const pl = []; for (let i = 0; i < names.length; i++) pl.push(await api('savePerson', { token, person: { name: names[i], gender: [2, 3, 6, 7].includes(i) ? 'P' : 'L' }, photoData: asli }));
  const loginAs = async (u) => api('login', { username: u, pin: '123456', token: '' });
  const b = await chromium.launch(), errs = [];
  const watch = (p, tag) => { p.on('pageerror', (e) => errs.push(tag + ': ' + e.message)); p.on('console', (m) => { if (m.type() === 'error' && !/Failed to load resource|favicon|navigator\.vibrate/.test(m.text())) errs.push(tag + ' console: ' + m.text()); }); };
  const open = async (vp, auth, tag, url) => {
    const ctx = await L.ctx(b, { viewport: vp, deviceScaleFactor: 2 }); const pg = await ctx.newPage(); watch(pg, tag);
    await pg.goto(B + '/'); if (auth) await pg.evaluate((a) => localStorage.setItem('paddoc_auth', JSON.stringify(a)), auth);
    await pg.goto(B + (url || '/')); return pg;
  };
  // v2.9.1: yang login mendarat di Home; tes yang butuh dashboard masuk lewat logo
  const toDash = async (pg) => { await pg.waitForSelector('.v-home, .v-dash, .v-board', { timeout: 15000 }); if (await pg.$('.v-home')) { await pg.evaluate(() => document.querySelector('.topbar .brand').click()); await pg.waitForSelector('.v-dash, .v-board', { timeout: 10000 }); } };
  step('form rencana: jam selesai');
  const ha = await open({ width: 1180, height: 820 }, adm, 'admin', '/');
  await ha.waitForSelector('[data-act="newSession"]', { timeout: 15000 }); await ha.click('[data-act="newSession"] >> nth=0'); await ha.waitForSelector('#su-end');
  ok(await ha.inputValue('#su-end') === '21:30' && /Booking 2 jam/.test(await ha.textContent('.setup')), 'setup: jam selesai bawaan 21.30, keterangan "Booking 2 jam"');
  await ha.fill('#su-end', '22:30'); await ha.dispatchEvent('#su-end', 'change'); await ha.waitForTimeout(300);
  ok(/Booking 3 jam/.test(await ha.textContent('.setup')) && /19\.30–22\.30/.test(await ha.textContent('.startbar')), 'ubah jam selesai: durasi & rentang jam ikut berubah');
  const H = 3600e3, now = Date.now(), when = now - 25 * 60000, until = when + 3 * H;
  const r = await api('createSession', { token, setup: { name: 'Booking 3 Jam', format: 'americano', courts: [{ name: 'Court 1' }, { name: 'Court 2' }], playerIds: pl.slice(0, 6).map((x) => x.id),
    plan: { when, until, whenText: 'Hari ini · ' + hh(when) + '–' + hh(until) + ' WIB', venue: { name: 'Padel Doc Arena' }, theme: 'court' } } });
  const sid = r.sid;
  step('pemain memilih jam hadir di lobi');
  const gita = await loginAs(pl[6].username);
  const hg = await open({ width: 390, height: 844 }, gita, 'hp-gita', '/?lobby=' + sid);
  await hg.waitForSelector('[data-lb="join"]', { timeout: 10000 }); await hg.click('[data-lb="join"]'); await hg.waitForSelector('.slot-opt');
  const opts = await hg.$$eval('.slot-opt', (e) => e.map((x) => x.textContent.trim()));
  ok(opts[0].startsWith('Full') && opts.filter((x) => /^\d\d\.\d\d–\d\d\.\d\d$/.test(x)).length === 5, 'pilihan: Full + 3 pilihan 1 jam + 2 pilihan 2 jam (' + opts.length + ')');
  const w2 = hh(when + H) + '–' + hh(when + 2 * H);
  await hg.screenshot({ path: OUT + '/01-slot-picker.png' });
  await hg.click('.slot-opt:text-is("' + w2 + '")'); await hg.waitForTimeout(1200);
  let pv = (await api('poll', {})).plans[0].rsvp.find((x) => x.pid === pl[6].id);
  ok(pv && pv.from === when + H && pv.to === when + 2 * H, 'Gita tercatat hadir ' + w2);
  ok((await hg.textContent('.lb-roster')).includes('Kamu · ' + w2), 'daftar hadir menampilkan jam Gita');
  const hours = await hg.$$eval('.lb-hours b', (e) => e.map((x) => x.textContent.replace(/\s+/g, ' ').trim()));
  ok(hours.length === 3 && / 6$/.test(hours[0]) && / 7$/.test(hours[1]) && / 6$/.test(hours[2]), 'jumlah pemain per jam: ' + hours.join(' | '));
  await hg.click('[data-lb="slot"]'); await hg.waitForSelector('.slot-opt.on');
  const w3 = hh(when + H) + '–' + hh(until);
  await hg.click('.slot-opt:text-is("' + w3 + '")'); await hg.waitForTimeout(1200);
  pv = (await api('poll', {})).plans[0].rsvp.find((x) => x.pid === pl[6].id);
  ok(pv.to === until, 'Ubah jam hadir: Gita jadi 2 jam (' + w3 + ')');
  await hg.screenshot({ path: OUT + '/02-lobby-hours.png' });
  // Hana: jam habis sebentar lagi (untuk menguji alarm server)
  const hana = await loginAs(pl[7].username);
  await api('act', { token: hana.token, sid, type: 'rsvp', payload: { on: true, from: when, to: Date.now() + 11 * 60000 + 20000 } });
  step('sesi berjalan: menunggu jamnya & jam habis');
  await api('act', { token, sid, type: 'startPlan', payload: {} });
  let S = (await api('poll', {})).S;
  ok(S.parts[pl[6].id].paused && S.parts[pl[6].id].timeOff === 'wait' && S.parts[pl[7].id].active && !S.parts[pl[7].id].paused, 'mulai: Gita menunggu jamnya, Hana ikut diundi');
  await hg.goto(B + '/'); await toDash(hg); await hg.waitForSelector('.mystatus', { timeout: 10000 });
  ok(new RegExp('Jam mainmu mulai ' + hh(when + H).replace('.', '\\.')).test(await hg.textContent('.mystatus')), 'HP Gita: "Jam mainmu mulai ' + hh(when + H) + '"');
  ok((await hg.textContent('.bench-wrap')).includes('mulai ' + hh(when + H)), 'antrean menampilkan "mulai ' + hh(when + H) + '" untuk Gita');
  await hg.screenshot({ path: OUT + '/03-wait.png' });
  await hg.click('.mystatus [data-act="selfReady"]'); await hg.waitForTimeout(1200);
  S = (await api('poll', {})).S;
  ok(!S.parts[pl[6].id].paused && S.avail[pl[6].id].st === 'in', 'Gita datang lebih awal → ikut diundi');
  const hh7 = await open({ width: 390, height: 844 }, hana, 'hp-hana', '/'); await toDash(hh7);
  await hh7.waitForSelector('.mystatus', { timeout: 10000 });
  console.log('  menunggu alarm server (jam Hana habis)…');
  let done = false; for (let i = 0; i < 60 && !done; i++) { await new Promise((res) => setTimeout(res, 2000)); S = (await api('poll', {})).S; done = !S.parts[pl[7].id].active; }
  ok(done && S.parts[pl[7].id].timeOff === 'done', 'alarm server: 10 menit sebelum jamnya habis, Hana berhenti diundi tanpa ada yang menekan apa pun');
  await hh7.waitForFunction(() => /Jam mainmu sudah selesai/.test(document.querySelector('.mystatus') && document.querySelector('.mystatus').textContent), null, { timeout: 8000 }).catch(() => {});
  ok(/Jam mainmu sudah selesai/.test(await hh7.textContent('.mystatus')), 'HP Hana berubah sendiri: "Jam mainmu sudah selesai" + Main lagi');
  await hh7.screenshot({ path: OUT + '/04-done.png' });
  ok(!errs.length, 'tanpa error JS' + (errs.length ? ': ' + errs.slice(0, 5).join(' | ') : ''));
  await b.close();
})().catch((e) => { console.error(e); process.exitCode = 1; });
